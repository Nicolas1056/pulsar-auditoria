package com.metrofico.pulsar.api.perf;

import com.metrofico.pulsar.api.hub.ClientOptions;
import com.metrofico.pulsar.api.legit.GameSignals;

public final class FrameFlags {
   public static boolean perf;
   public static volatile boolean smartLeaves;
   public static volatile boolean tabCache;
   public static volatile boolean chatCache;
   public static volatile boolean chatRewrap;
   public static boolean cullEntities;
   public static boolean cullPlayers;
   public static boolean occludePlayers;
   public static boolean ownNametag;
   public static boolean invisibleNametags = true;
   public static boolean blockEntityLoop = true;
   public static boolean cullBlockEntities;
   public static double beDistanceSq = 4096.0;
   public static boolean textBatch;
   public static boolean terrainRegions;
   public static boolean faceCulling;
   public static boolean terrainMultidraw;
   public static boolean compactVertices;
   public static boolean gpuOcclusion;
   public static boolean entityBatch;
   public static boolean uiBatch;
   public static boolean cloudCache;
   public static boolean visibility;
   public static boolean labelBatch;
   public static boolean entityLod;
   public static boolean entityCache;
   public static boolean entityCacheCombat;
   public static boolean entityCacheMaps;
   public static boolean entityCacheMerge;
   public static boolean clientArrays;
   public static boolean drawFirst;
   public static boolean shadowBatch;
   public static boolean asyncNearChunks;
   public static boolean signText;
   public static boolean sectionMatrix;
   public static boolean textureUpload;
   public static boolean batchDeletes;
   public static boolean lazyBuffers;
   public static boolean signBatch;
   public static double animDistanceSq;
   public static boolean spriteCulling;
   public static boolean fastMath;
   public static boolean pacer = true;
   public static boolean fog = true;
   public static boolean sky = true;
   public static boolean sunMoon = true;
   public static boolean stars = true;
   public static boolean vignette = true;
   public static boolean weather = true;
   public static boolean animWater = true;
   public static boolean animLava = true;
   public static boolean animFire = true;
   public static boolean animPortal = true;
   public static int chunkUpdates;
   public static boolean dynamicUpdates = true;
   public static boolean legitSensors = true;
   public static boolean refreshed;

   private FrameFlags() {
   }

   public static void refresh() {
      ClientOptions o = ClientOptions.get();
      refreshed = true;
      perf = o.enabled("perf");
      cullEntities = perf && o.bool("perf.cullEntities", true);
      cullPlayers = o.bool("perf.cullPlayers", false);
      occludePlayers = perf && o.bool("perf.occludePlayers", true);
      ownNametag = o.enabled("nametag");
      invisibleNametags = o.bool("fix.invisibleNametags", true);
      blockEntityLoop = o.bool("fix.blockEntityLoop", true);
      cullBlockEntities = perf && o.bool("perf.cullBlockEntities", true);
      textBatch = perf && o.bool("perf.textCache", true);
      terrainRegions = perf && o.bool("perf.terrainRegions", true);
      faceCulling = perf && o.bool("perf.faceCulling", true);
      smartLeaves = perf && o.bool("perf.smartLeaves", true);
      tabCache = perf && o.bool("perf.tabCache", true);
      chatCache = perf && o.bool("perf.chatCache", true);
      chatRewrap = perf && o.bool("perf.chatRewrap", true);
      terrainMultidraw = perf && o.bool("perf.terrainMultidraw", true);
      compactVertices = perf && o.bool("perf.compactVertices", true);
      gpuOcclusion = perf && o.bool("perf.gpuOcclusion", true);
      entityBatch = perf && o.bool("perf.entityBatch", true);
      uiBatch = perf && o.bool("perf.uiBatch", true);
      cloudCache = perf && o.bool("perf.cloudCache", true);
      visibility = perf && o.bool("perf.visibility", true);
      labelBatch = perf && o.bool("perf.labelBatch", true);
      entityLod = perf && o.bool("perf.entityLod", true);
      entityCache = perf && o.bool("perf.entityCache", true);
      entityCacheCombat = perf && o.bool("perf.entityCacheCombat", true);
      entityCacheMaps = perf && o.bool("perf.entityCacheMaps", true);
      entityCacheMerge = perf && o.bool("perf.entityCacheMerge", true);
      clientArrays = perf && o.bool("perf.clientArrays", true);
      drawFirst = perf && o.bool("perf.drawFirst", true);
      shadowBatch = perf && o.bool("perf.shadowBatch", true);
      signText = perf && o.bool("perf.signText", true);
      sectionMatrix = perf && o.bool("perf.sectionMatrix", true);
      textureUpload = perf && o.bool("perf.textureUpload", true);
      batchDeletes = perf && o.bool("perf.batchDeletes", true);
      lazyBuffers = perf && o.bool("perf.lazyBuffers", true);
      signBatch = perf && o.bool("perf.signBatch", true);
      asyncNearChunks = perf && o.bool("perf.asyncNearChunks", true);
      int animDistance = o.integer("perf.animDistance", 64);
      animDistanceSq = (double)animDistance * animDistance;
      spriteCulling = perf && o.bool("perf.spriteCulling", true);
      fastMath = perf && o.bool("perf.fastMath", false);
      pacer = perf && o.bool("perf.pacer", true);
      FramePacer.enabled(pacer);
      fog = !perf || o.bool("perf.fog", true);
      sky = !perf || o.bool("perf.sky", true);
      sunMoon = !perf || o.bool("perf.sunMoon", true);
      stars = !perf || o.bool("perf.stars", true);
      vignette = !perf || o.bool("perf.vignette", true);
      weather = !perf || o.bool("perf.weather", true);
      animWater = !perf || o.bool("perf.animWater", true);
      animLava = !perf || o.bool("perf.animLava", true);
      animFire = !perf || o.bool("perf.animFire", true);
      animPortal = !perf || o.bool("perf.animPortal", true);
      chunkUpdates = perf ? o.integer("perf.chunkUpdates", 0) : 0;
      dynamicUpdates = o.bool("perf.dynamicUpdates", true);
      legitSensors = o.bool("legit.sensors", true);
      GameSignals.enabled(legitSensors);
      int d = o.integer("perf.beDistance", 64);
      beDistanceSq = (double)d * d;
   }
}
